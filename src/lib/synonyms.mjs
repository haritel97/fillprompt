/** Expand one query word with its aliases (word itself first). */
export const variants = (w) => [w, ...(ALIAS[w] || [])];

/** True when haystack matches word or any of its aliases. */
export const wordHit = (haystack, w) => {
  const h = haystack.toLowerCase();
  for (const a of variants(w.toLowerCase())) if (h.includes(a)) return true;
  return false;
};
